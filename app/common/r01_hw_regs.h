#ifndef R01_HW_REGS_H
#define R01_HW_REGS_H

/* CPU I/O map ($FE00-$FEFF). Shared by emu, Studio PRG export, and game asm. */

#define R01_PORT_PPUCTRL 0xFE00u
#define R01_PORT_PPUSTATUS 0xFE01u
#define R01_PORT_SCROLL_X 0xFE02u
#define R01_PORT_SCROLL_Y 0xFE03u
#define R01_PORT_RASTER_Y 0xFE04u
#define R01_PORT_RASTER_CTRL 0xFE05u
#define R01_PORT_BG0_SCROLL_X 0xFE06u
#define R01_PORT_BG0_SCROLL_Y 0xFE07u
#define R01_PORT_PAL_ADDR 0xFE08u
#define R01_PORT_PAL_DATA 0xFE09u
#define R01_PORT_VRAM_ADDR_LO 0xFE10u
#define R01_PORT_VRAM_ADDR_HI 0xFE11u
#define R01_PORT_VRAM_DATA 0xFE12u
#define R01_PORT_OAM_ADDR 0xFE20u
#define R01_PORT_OAM_DATA 0xFE21u
#define R01_PORT_CARTEE_CMD 0xFE22u
#define R01_PORT_CARTEE_ADDR 0xFE23u
#define R01_PORT_CARTEE_DATA 0xFE24u
#define R01_PORT_WORLD 0xFE30u
#define R01_PORT_PAD0 0xFE60u
#define R01_PORT_PAD1 0xFE61u
#define R01_PORT_MEEPROM_AL 0xFE70u
#define R01_PORT_MEEPROM_AH 0xFE71u
#define R01_PORT_MEEPROM_DATA 0xFE72u
#define R01_PORT_MAP_LO 0xFE90u
#define R01_PORT_MAP_MID 0xFE91u
#define R01_PORT_MAP_HI 0xFE92u
#define R01_PORT_MAP_DATA 0xFE93u

/* PPUCTRL ($FE00) -- docs/graphics.md */
#define R01_PPUCTRL_L1_EN 0x01u
#define R01_PPUCTRL_L0_EN 0x02u
#define R01_PPUCTRL_SPR_EN 0x04u
#define R01_PPUCTRL_L0_CAM_SHIFT 3u
#define R01_PPUCTRL_L0_CAM_MASK 0x18u
#define R01_PPUCTRL_L1_CAM_SHIFT 5u
#define R01_PPUCTRL_L1_CAM_MASK 0x60u
#define R01_PPUCTRL_NMI_EN 0x80u
#define R01_PPUCTRL_BOOT (R01_PPUCTRL_L1_EN | R01_PPUCTRL_L0_EN | R01_PPUCTRL_SPR_EN)

#define R01_PPUSTATUS_VBLANK 0x80u
#define R01_PPUSTATUS_HIT 0x40u

/* Cart save mailbox (24C64, 8 KB). */
#define R01_CARTEE_CMD_READ 0x80u
#define R01_CARTEE_CMD_WRITE 0x40u
#define R01_CARTEE_BYTES 8192u

/* Machine EEPROM (1284 internal, 4 KB). */
#define R01_MEEPROM_BYTES 4096u

#endif
