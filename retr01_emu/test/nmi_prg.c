#include <stddef.h>
#include <stdint.h>
#include <string.h>

void retr01_test_fill_nmi_prg(uint8_t *prg, size_t size)
{
    if (!prg || size < 0x8000) {
        return;
    }
    memset(prg, 0xEA, size);

    /* reset at $8000 */
    prg[0x0000] = 0xA9; /* LDA #$AA */
    prg[0x0001] = 0xAA;
    prg[0x0002] = 0x8D; /* STA $0200 */
    prg[0x0003] = 0x00;
    prg[0x0004] = 0x02;
    prg[0x0005] = 0xA9; /* LDA #$80 */
    prg[0x0006] = 0x80;
    prg[0x0007] = 0x8D; /* STA $FE00  NMI enable */
    prg[0x0008] = 0x00;
    prg[0x0009] = 0xFE;
    prg[0x000A] = 0x58; /* CLI */
    prg[0x000B] = 0x4C; /* JMP $800B */
    prg[0x000C] = 0x0B;
    prg[0x000D] = 0x80;

    /* nmi at $8010 */
    prg[0x0010] = 0xEE; /* INC $0201 */
    prg[0x0011] = 0x01;
    prg[0x0012] = 0x02;
    prg[0x0013] = 0xAD; /* LDA $FE60 */
    prg[0x0014] = 0x60;
    prg[0x0015] = 0xFE;
    prg[0x0016] = 0x8D; /* STA $0202 */
    prg[0x0017] = 0x02;
    prg[0x0018] = 0x02;
    prg[0x0019] = 0x40; /* RTI */

    prg[0x7FFA] = 0x10; /* NMI */
    prg[0x7FFB] = 0x80;
    prg[0x7FFC] = 0x00; /* RESET */
    prg[0x7FFD] = 0x80;
    prg[0x7FFE] = 0x10; /* IRQ */
    prg[0x7FFF] = 0x80;
}
