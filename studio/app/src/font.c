static int glyph_index(char c) {
    if (c == ' ') {
        return 0;
    }
    if (c >= '0' && c <= '9') {
        return 1 + (c - '0');
    }
    if (c >= 'a' && c <= 'z') {
        c = (char)(c - 'a' + 'A');
    }
    if (c >= 'A' && c <= 'Z') {
        return 11 + (c - 'A');
    }
    switch (c) {
    case '.':
        return 37;
    case ':':
        return 38;
    case '-':
        return 39;
    case '/':
        return 40;
    case '_':
        return 41;
    case '+':
        return 42;
    case '=':
        return 43;
    case '(':
        return 44;
    case ')':
        return 45;
    default:
        return 0; /* unknown → blank */
    }
}

void font_draw(SDL_Renderer *r, int x, int y, const char *text, Uint8 R, Uint8 G, Uint8 B) {
    int cx = x;
    SDL_SetRenderDrawColor(r, R, G, B, 255);
    for (; text && *text; text++) {
        const uint8_t *g = GLYPHS[glyph_index(*text)];
        int row, col;
        for (row = 0; row < 7; row++) {
            for (col = 0; col < 5; col++) {
                if (g[row] & (0x10 >> col)) {
                    SDL_RenderDrawPoint(r, cx + col, y + row);
                }
            }
        }
        cx += 6;
    }
}
