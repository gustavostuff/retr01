static int glyph_index(char c) {
    if (c == ' ') {
        return 0;
    }
    if (c >= '0' && c <= '9') {
        return 1 + (c - '0');
    }
    if (c >= 'a' && c <= 'z') {
        c = (char)(c - 'a' + 'A');
    }
    switch (c) {
    case 'A':
        return 11;
    case 'B':
        return 12;
    case 'C':
        return 13;
    case 'D':
        return 14;
    case 'E':
        return 15;
    case 'F':
        return 16;
    case 'G':
        return 17;
    case 'H':
        return 18;
    case 'I':
        return 19;
    case 'K':
        return 20;
    case 'L':
        return 21;
    case 'M':
        return 22;
    case 'N':
        return 23;
    case 'O':
        return 24;
    case 'P':
        return 25;
    case 'R':
        return 26;
    case 'S':
        return 27;
    case 'T':
        return 28;
    case 'U':
        return 29;
    case 'V':
        return 30;
    case 'W':
        return 31;
    case 'Y':
        return 32;
    case '.':
        return 33;
    case ':':
        return 34;
    case '-':
        return 35;
    case '/':
        return 36;
    case '_':
        return 37;
    default:
        return 0;
    }
}

void font_draw(SDL_Renderer *r, int x, int y, const char *text, Uint8 R, Uint8 G, Uint8 B) {
    int cx = x;
    SDL_SetRenderDrawColor(r, R, G, B, 255);
    for (; text && *text; text++) {
        const uint8_t *g = GLYPHS[glyph_index(*text)];
        int row, col;
        for (row = 0; row < 7; row++) {
            for (col = 0; col < 5; col++) {
                if (g[row] & (0x10 >> col)) {
                    SDL_RenderDrawPoint(r, cx + col, y + row);
                }
            }
        }
        cx += 6;
    }
}
